create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role text not null check (role in ('student', 'faculty', 'admin')),
  roll_no text unique,
  department text,
  year text,
  section text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  faculty_id bigint not null references public.profiles(id) on delete restrict,
  department text not null,
  year text not null,
  section text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  category text not null check (category in ('general', 'exam', 'assignment', 'event', 'placement', 'holiday')),
  priority text not null check (priority in ('normal', 'important', 'urgent')),
  department text,
  year text,
  section text,
  due_date date,
  needs_ack boolean not null default false,
  status text not null check (status in ('draft', 'published')),
  publish_at timestamptz not null default now(),
  created_by bigint not null references public.profiles(id) on delete restrict,
  pinned boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.read_receipts (
  notice_id bigint not null references public.notices(id) on delete cascade,
  user_id bigint not null references public.profiles(id) on delete cascade,
  read_at timestamptz not null default now(),
  ack_at timestamptz,
  primary key (notice_id, user_id)
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  unit text not null,
  title text not null,
  description text,
  type text not null check (type in ('file', 'link')),
  file_name text,
  link text,
  storage_path text unique,
  visibility text not null check (visibility in ('draft', 'published')),
  uploaded_by bigint not null references public.profiles(id) on delete restrict,
  uploaded_at timestamptz not null default now(),
  version integer not null default 1 check (version > 0),
  check ((type = 'file' and file_name is not null and storage_path is not null) or (type = 'link' and link is not null))
);

create table if not exists public.material_views (
  id bigint generated by default as identity primary key,
  material_id bigint not null references public.materials(id) on delete cascade,
  user_id bigint not null references public.profiles(id) on delete cascade,
  viewed_at timestamptz not null default now()
);

create table if not exists public.bookmarks (
  user_id bigint not null references public.profiles(id) on delete cascade,
  item_type text not null check (item_type in ('notice', 'material')),
  item_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (user_id, item_type, item_id)
);

create index if not exists notices_created_by_idx on public.notices(created_by);
create index if not exists notices_audience_idx on public.notices(department, year, section, status, publish_at);
create index if not exists materials_course_visibility_idx on public.materials(course_id, visibility);
create index if not exists material_views_material_idx on public.material_views(material_id);
create index if not exists bookmarks_item_idx on public.bookmarks(item_type, item_id);

create or replace function public.current_profile_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.profiles where auth_user_id = auth.uid() and active limit 1
$$;

create or replace function public.current_profile_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where auth_user_id = auth.uid() and active limit 1
$$;

create or replace function public.is_profile_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_profile_role() = 'admin', false)
$$;

create or replace function public.matches_current_audience(target_department text, target_year text, target_section text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.auth_user_id = auth.uid() and p.active and p.role = 'student'
      and (target_department is null or target_department = '' or target_department = p.department)
      and (target_year is null or target_year = '' or target_year = p.year)
      and (target_section is null or target_section = '' or target_section = p.section)
  )
$$;

create or replace function public.get_student_email(p_roll_no text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select email from public.profiles
  where role = 'student' and active and lower(roll_no) = lower(trim(p_roll_no))
  limit 1
$$;

create or replace function public.can_access_material_file(object_name text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.materials m
    join public.courses c on c.id = m.course_id
    where m.storage_path = object_name
      and (
        public.is_profile_admin()
        or m.uploaded_by = public.current_profile_id()
        or (
          m.visibility = 'published'
          and exists (
            select 1 from public.profiles p
            where p.auth_user_id = auth.uid() and p.active and p.role = 'student'
              and p.department = c.department and p.year = c.year and p.section = c.section
          )
        )
      )
  )
$$;

create or replace view public.profile_directory with (security_invoker = false) as
  select id, name, role
  from public.profiles;
grant select on public.profile_directory to authenticated;

create or replace view public.staff_directory with (security_invoker = false) as
  select id, name, role, department, year, section, active
  from public.profiles
  where public.current_profile_role() in ('faculty', 'admin');
grant select on public.staff_directory to authenticated;

