create policy "profiles visible to self and admins" on public.profiles
  for select to authenticated
  using (auth_user_id = auth.uid() or public.is_profile_admin());
create policy "admins update profiles" on public.profiles
  for update to authenticated using (public.is_profile_admin()) with check (public.is_profile_admin());

create policy "courses visible to authenticated users" on public.courses
  for select to authenticated using (true);
create policy "admins manage courses" on public.courses
  for all to authenticated using (public.is_profile_admin()) with check (public.is_profile_admin());

create policy "notices visible by role and audience" on public.notices
  for select to authenticated using (
    public.is_profile_admin()
    or created_by = public.current_profile_id()
    or (
      status = 'published' and publish_at <= now()
      and public.matches_current_audience(department, year, section)
    )
  );
create policy "staff create notices" on public.notices
  for insert to authenticated with check (
    created_by = public.current_profile_id()
    and public.current_profile_role() in ('faculty', 'admin')
  );
create policy "owners and admins update notices" on public.notices
  for update to authenticated
  using (created_by = public.current_profile_id() or public.is_profile_admin())
  with check (created_by = public.current_profile_id() or public.is_profile_admin());
create policy "owners and admins delete notices" on public.notices
  for delete to authenticated using (created_by = public.current_profile_id() or public.is_profile_admin());

create policy "read receipts visible to reader and notice staff" on public.read_receipts
  for select to authenticated using (
    user_id = public.current_profile_id()
    or public.is_profile_admin()
    or exists (select 1 from public.notices n where n.id = notice_id and n.created_by = public.current_profile_id())
  );
create policy "students create own read receipts" on public.read_receipts
  for insert to authenticated with check (
    user_id = public.current_profile_id() and public.current_profile_role() = 'student'
  );
create policy "students update own read receipts" on public.read_receipts
  for update to authenticated
  using (user_id = public.current_profile_id() and public.current_profile_role() = 'student')
  with check (user_id = public.current_profile_id() and public.current_profile_role() = 'student');

create policy "materials visible to owner staff and enrolled class" on public.materials
  for select to authenticated using (
    public.is_profile_admin()
    or uploaded_by = public.current_profile_id()
    or exists (
      select 1 from public.courses c
      join public.profiles p on p.auth_user_id = auth.uid() and p.active and p.role = 'student'
      where c.id = course_id and c.department = p.department and c.year = p.year and c.section = p.section
        and visibility = 'published'
    )
  );
create policy "staff upload materials" on public.materials
  for insert to authenticated with check (
    uploaded_by = public.current_profile_id() and public.current_profile_role() in ('faculty', 'admin')
  );
create policy "owners and admins update materials" on public.materials
  for update to authenticated
  using (uploaded_by = public.current_profile_id() or public.is_profile_admin())
  with check (uploaded_by = public.current_profile_id() or public.is_profile_admin());
create policy "owners and admins delete materials" on public.materials
  for delete to authenticated using (uploaded_by = public.current_profile_id() or public.is_profile_admin());

create policy "material views visible to reader and owner staff" on public.material_views
  for select to authenticated using (
    user_id = public.current_profile_id()
    or public.is_profile_admin()
    or exists (select 1 from public.materials m where m.id = material_id and m.uploaded_by = public.current_profile_id())
  );
create policy "students record own material views" on public.material_views
  for insert to authenticated with check (
    user_id = public.current_profile_id() and public.current_profile_role() = 'student'
  );

create policy "users manage their own bookmarks" on public.bookmarks
  for all to authenticated
  using (user_id = public.current_profile_id())
  with check (user_id = public.current_profile_id());

create or replace function public.remove_deleted_notice_bookmarks()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from public.bookmarks where item_type = 'notice' and item_id = old.id;
  return old;
end;
$$;
create or replace function public.remove_deleted_material_bookmarks()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from public.bookmarks where item_type = 'material' and item_id = old.id;
  return old;
end;
$$;
drop trigger if exists notices_remove_bookmarks on public.notices;
create trigger notices_remove_bookmarks after delete on public.notices
  for each row execute function public.remove_deleted_notice_bookmarks();
drop trigger if exists materials_remove_bookmarks on public.materials;
create trigger materials_remove_bookmarks after delete on public.materials
  for each row execute function public.remove_deleted_material_bookmarks();

