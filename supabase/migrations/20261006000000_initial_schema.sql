create policy "staff upload their own material files" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'materials'
    and (storage.foldername(name))[1] = public.current_profile_id()::text
    and public.current_profile_role() in ('faculty', 'admin')
  );
create policy "authorized users read material files" on storage.objects
  for select to authenticated using (bucket_id = 'materials' and public.can_access_material_file(name));
create policy "owners and admins delete material files" on storage.objects
  for delete to authenticated using (
    bucket_id = 'materials'
    and ((storage.foldername(name))[1] = public.current_profile_id()::text or public.is_profile_admin())
  );

